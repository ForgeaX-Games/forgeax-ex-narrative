/**
 * structural-clarity.ts —— F3 补齐的四项结构性缺口的通用渲染器。
 *
 * 来源：MyFile/script-to-story-node-prompts.ts（同一份 kino-factory 提示词，narrative-craft.ts
 * 已吸收过它的写法条款；这里吸收的是它的**结构设计**，不是文字条款）。那份提示词有四样
 * 东西是"标杆有、我们的席位没有"的，但不是哪条缺陷造成的——是提示词的组织方式本身缺了这四类
 * 说明，写不写都不影响某一次具体生成对不对，但长期会让模型在材料冲突/模式误判/找错字段/
 * 输出前不自检这几类问题上反复摔同一个坑：
 *
 * 1. **输入冲突优先级链**：一个 step 的提示词经常同时塞进用户需求、上游结构、世界观、
 *    角色档案、全局调控参数等好几处材料。这些材料在具体一次生成里完全可能互相矛盾
 *    （初步大纲写的性格 vs 角色档案后来定的性格），模型该信哪个，我们从没明说过，
 *    模型只能自己猜——猜的结果不可控。原文的解法（`buildStep2Prompt` 那行长长的
 *    "输入冲突优先级"）是显式给一条全序，让裁决可复现。
 * 2. **模式分流的唯一判定源**：有些行为分支本来已经由代码算好了唯一答案（本次要不要
 *    多结局、这是不是开端节点、复杂度档位多大），但提示词只是把算好的结果摆在那里，
 *    没有明说"这就是唯一依据，不要自己再读一遍材料重新判断"——模型有时会绕开这个
 *    结论，自己从字里行间另外读出一个不一致的判断（比如明明没检测到多结局要求，
 *    模型自己觉得"这个故事应该有好几种结局"）。原文用"是唯一判定源"这句话把这类
 *    字段钉死，不容模型另作他想。
 * 3. **概念层到字段层的映射说明**：cot/task_spec 里大量创作性概念（"叙事单元"
 *    "个性碎片""代价档"）本身不是字段名，模型读完概念之后要素怎么落进 JSON 的哪个
 *    键，全靠它自己在 output 段猜。多数时候猜得对，但复杂概念（如"开端节点的四项
 *    个性要求"要塞进一个自由文本字段而非独立键）容易被漏落或者错落进不该放的字段。
 *    显式给一张"概念 → 字段"对照表，把这层猜测去掉。
 * 4. **输出前自检清单**：席位内部散落的"自检：xxx"是嵌在长段说明文字中的一句话，
 *    容易被正文淹没；标杆把它单独摘成 checkbox 列表放在输出格式前，且明确要求
 *    "不过就静默修正后重走，不要把检查过程写进输出"——这条元指令本身也值得抄，
 *    否则模型有时会把自检过程当成内容的一部分写进 JSON。
 *
 * 用法：四个 builder 各自独立，按需在 PromptComposer.blocks 里挂成新槽位，
 * systemBlockOrder 里推荐紧跟 cot 之后、output 之前，顺序：
 *   cot → priority_chain → mode_source → concept_mapping → self_check → output
 * （先讲流程，再定材料冲突时怎么裁决，再钉死不许重新判断的字段，再给概念到字段的
 *  对照表，最后自检收口，然后才是输出格式——每一步都在为下一步收窄不确定性）。
 */

/** 输入冲突优先级链：items 按优先级从高到低排列，每项一句话说清"是什么、为什么排这里"。 */
export function inputPriorityChain(items: readonly string[]): string {
  return `## 输入冲突优先级

本席的材料来自上游好几处，一次生成里完全可能互相矛盾（比如两处对同一件事的说法不一致）。
出现矛盾时按下列顺序从高到低裁决——排位靠前的事实不得被排位靠后的材料覆盖、稀释或另作解读：

${items.map((it, i) => `${i + 1}. ${it}`).join("\n")}`;
}

/** 模式判定源：statements 逐条声明"某个行为分支已经由谁唯一决定"，不容模型重新判断。 */
export function modeDispatchSource(statements: readonly string[]): string {
  return `## 判定已定，不要重新猜

下面这些分支性判断，答案已经由括号内指出的唯一依据给定，不要自己从材料字面另外揣测
出一个不一致的结论——揣测的结果只会和已经算好的答案打架：

${statements.map((s) => `- ${s}`).join("\n")}`;
}

/** 概念到字段的映射说明：rows 把提示词里的创作性说法对应到输出 JSON 的具体字段路径。 */
export function conceptFieldMapping(rows: ReadonlyArray<{ concept: string; field: string }>): string {
  return `## 概念 → 字段对照

上面用创作语言描述的这些东西，最终要落进输出 JSON 的具体字段，不是"意思到了"就算完成：

${rows.map((r) => `- ${r.concept} → \`${r.field}\``).join("\n")}`;
}

/** 输出前自检清单：items 是待勾选的检查项，统一带上"不过则静默修正后重走"的元指令。 */
export function preOutputChecklist(items: readonly string[]): string {
  return `## 输出前自检（每条都过才允许输出；任一条不过，内部静默修正后重新过一遍这份清单，
不要把检查过程写进输出）

${items.map((it) => `☐ ${it}`).join("\n")}`;
}
