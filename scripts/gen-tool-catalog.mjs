#!/usr/bin/env node
// Derives the extension's tool catalog from forgeax-extension.json so the Codex
// surface can never drift from the Studio surface. Writes three artifacts:
//   extension/src/catalog.generated.ts    — runtime validation for the `call` verb
//   extension/skills/.../SKILL.md         — the tool list between the TOOLS markers
//   extension/.codex-plugin/plugin.json   — Codex's manifest, version-locked to package.json
// One directory therefore satisfies both hosts: @forgeax/game reads
// extension.json, Codex reads .codex-plugin/plugin.json, and they share the
// same SKILL.md and cli.mjs.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(resolve(root, 'forgeax-extension.json'), 'utf8'));

const tools = manifest.contributes.tools
  .filter((tool) => tool.exposedToAI !== false)
  .map((tool) => {
    const name = tool.id.replace(/^narrative:/u, '');
    // `args` is either a path to a schema file or the schema inlined.
    const schema = typeof tool.args === 'string'
      ? JSON.parse(readFileSync(resolve(root, tool.args), 'utf8'))
      : tool.args;
    const properties = schema.properties ?? {};
    return {
      name,
      id: tool.id,
      description: tool.description.zh,
      params: Object.keys(properties),
      hints: Object.fromEntries(
        Object.entries(properties)
          .filter(([, value]) => typeof value?.description === 'string')
          .map(([key, value]) => [key, value.description]),
      ),
      required: schema.required ?? [],
      requireConfirm: tool.requireConfirm === true,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));

const ts = `// GENERATED by scripts/gen-tool-catalog.mjs from forgeax-extension.json. Do not edit.

/** Service package the extension launches, pinned to the version it was built against. */
export const SERVICE_PACKAGE = ${JSON.stringify(pkg.name)};
export const SERVICE_VERSION = ${JSON.stringify(pkg.version)};

export interface CatalogEntry {
  readonly name: string;
  readonly id: string;
  readonly description: string;
  readonly params: readonly string[];
  readonly hints: Readonly<Record<string, string>>;
  readonly required: readonly string[];
  readonly requireConfirm: boolean;
}

export const CATALOG: readonly CatalogEntry[] = ${JSON.stringify(tools, null, 2)} as const;

export const BY_NAME = new Map(CATALOG.map((entry) => [entry.name, entry]));
`;
writeFileSync(resolve(root, 'extension/src/catalog.generated.ts'), ts);

const rows = tools.map((tool) => {
  const required = tool.required.length ? `必填 ${tool.required.join(', ')}` : '无必填参数';
  const optional = tool.params.filter((p) => !tool.required.includes(p));
  const confirm = tool.requireConfirm ? ' **需用户确认**' : '';
  return `- \`${tool.name}\` — ${tool.description}${confirm}\n  ${required}${optional.length ? `；可选 ${optional.join(', ')}` : ''}`;
});

const skillPath = resolve(root, 'extension/skills/narrative-workshop/SKILL.md');
const skill = readFileSync(skillPath, 'utf8');
const begin = '<!-- TOOLS:BEGIN -->';
const end = '<!-- TOOLS:END -->';
if (!skill.includes(begin) || !skill.includes(end)) {
  throw new Error(`SKILL.md is missing the ${begin} / ${end} markers`);
}
const updated = skill.replace(
  new RegExp(`${begin}[\\s\\S]*${end}`, 'u'),
  `${begin}\n${rows.join('\n')}\n${end}`,
);
writeFileSync(skillPath, updated);

// `@forgeax/game` rewrites {{CLI}} to the pinned invocation when it mounts the
// skill (manager.ts). Codex copies SKILL.md verbatim, so the placeholder would
// reach the model unresolved. Emit a second copy with the placeholder already
// bound to the plugin-local CLI, and point Codex's manifest at that directory.
// 两条安装路径各自产出一个同名 skill，Codex 两份都加载、不去重也不警告。两份都能跑通，
// 所以这里不改名，而是把「两份都在时选谁」写进描述——描述始终在上下文里，正文只有被选中
// 后才读得到。规则不是随手定的：宿主那条路独有项目级互斥锁（extension_busy），且
// projectRoot 由宿主解析游戏根给出，独立入口只能拿 cwd。
// 回退这半句是实测逼出来的：只写「优先用项目那份」时，项目那条路在禁网沙箱里拉不到包，
// 模型照着「命令失败就停下」的规则停住了，而旁边这个不需要网络的 CLI 就摆着没用上。
const STANDALONE_NOTE =
  ' This is the standalone installation: it needs no ForgeaX engine, no network and carries' +
  ' its own CLI. If a project-mounted narrative-workshop skill is also available, prefer that' +
  " one — it is pinned to the project's engine version and takes part in its extension lock." +
  ' But if its CLI cannot be fetched — no network, or the registry is unreachable — come back' +
  ' to this skill rather than giving up; this one runs from disk.';

const codexPreamble = `> A project-mounted \`narrative-workshop\` skill, if one exists, owns this workshop
> instead. Use it and ignore the steps below; it is pinned to the project's engine
> and holds the extension lock that keeps concurrent operations apart. Come back here
> only if that skill's CLI cannot be fetched — this one runs from disk and needs no network.

## Resolving the CLI

This plugin ships its own CLI at \`cli.mjs\`, two directories above this
SKILL.md. Resolve its absolute path once, then use it for every command below:

\`\`\`bash
NARRATIVE_CLI=<absolute path to this plugin's cli.mjs>
\`\`\`

Run the commands from the game directory, not from the plugin directory — the
CLI treats the working directory as the project root.

`;
// 只改 frontmatter 里那一行 description，不碰正文中任何以 description 开头的行。
const frontmatter = updated.match(/^---\n[\s\S]*?\n---\n/u);
if (!frontmatter) throw new Error('SKILL.md is missing its frontmatter block');
const codexFrontmatter = frontmatter[0].replace(/^(description: .*)$/mu, (line) => line + STANDALONE_NOTE);
if (codexFrontmatter === frontmatter[0]) throw new Error('SKILL.md frontmatter has no description line');

const codexSkill = (codexFrontmatter + updated.slice(frontmatter[0].length))
  .replace(/^# Narrative workshop\n\n/mu, `# Narrative workshop\n\n${codexPreamble}`)
  .replaceAll('{{CLI}}', 'node "$NARRATIVE_CLI"');
const codexSkillDir = resolve(root, 'extension/codex-skills/narrative-workshop');
mkdirSync(codexSkillDir, { recursive: true });
writeFileSync(resolve(codexSkillDir, 'SKILL.md'), codexSkill);

// Codex installs a plugin by copying its directory verbatim, so `extension/`
// doubles as the plugin root. Only the manifest name differs from @forgeax/game's.
const plugin = {
  name: 'narrative',
  version: pkg.version,
  description: pkg.description,
  author: { name: 'ForgeaX' },
  homepage: 'https://github.com/ForgeaX-Games/forgeax-ex-narrative',
  repository: pkg.repository.url.replace(/^git\+/u, '').replace(/\.git$/u, ''),
  license: pkg.license ?? 'UNLICENSED',
  keywords: ['narrative', 'game design', 'worldbuilding', 'storytelling', 'forgeax'],
  skills: './codex-skills/',
  interface: {
    displayName: '叙事工坊',
    shortDescription: '游戏叙事从一句话需求到可落地的世界观、角色与剧情',
    longDescription:
      '叙事工坊把一句话的故事需求展开成完整的游戏叙事资产：品类识别、世界观立柱、角色卡、' +
      '剧情结构与分支、质量校验与定向重写，全部产出可直接进入 ForgeaX 引擎的工程文件。',
    developerName: 'ForgeaX',
    category: 'Productivity',
    capabilities: ['Interactive', 'Read', 'Write'],
    websiteURL: 'https://github.com/ForgeaX-Games/forgeax-ex-narrative',
    defaultPrompt: [
      '帮我做一个赛博朋克侦探游戏的世界观和主角',
      '把这份设定文档扩写成完整的剧情结构',
      '检查当前叙事里的设定冲突并修掉',
    ],
    brandColor: '#1F7A5A',
  },
};
mkdirSync(resolve(root, 'extension/.codex-plugin'), { recursive: true });
writeFileSync(
  resolve(root, 'extension/.codex-plugin/plugin.json'),
  JSON.stringify(plugin, null, 2) + '\n',
);

console.log(
  `generated catalog: ${tools.length} tools -> extension/src/catalog.generated.ts + SKILL.md + .codex-plugin/plugin.json`,
);
